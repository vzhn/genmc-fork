/* Issue #137 (-exhaustive): t0's weak CAS on x1 succeeds reading the
 * initial value, with acquire order, so it is ordered before t0's later
 * store to x0 and is in the prefix of t2's store to x1, which t2 makes
 * after loading x0: TruSt does not offer the CAS to that store. A CAS
 * whose ordering or write part a write would change is revisitable by it
 * under -exhaustive, and the consistency of the revisited graph decides.
 *
 * Reading the store (or t1's fetch_add of it), the CAS fails, and the
 * load-buffering cycle (the CAS reads t2's store, t2's load reads t0's
 * later store) is inconsistent: IMM orders the CAS's read before t0's
 * later store ([Rex] ; po, a failing CAS's read is exclusive too), and
 * t2's fence orders its load before its store. The reference counted 16
 * such executions (474) while the events after a CAS did not depend on it
 * (from #133 to the fix of #137 and #145); the default exploration, rc11
 * and the reference agree on 458.
 *
 * (Generated by scripts/fuzz-c11.py, seed 64.)
 */
#include <pthread.h>
#include <stdatomic.h>

atomic_int x0;
atomic_int x1;

void *t0(void *arg)
{
	int r0 = 0;
	int r1 = 0;
	int r2 = 0;
	int r3 = 0;
	int r4 = 0;
	r0 = atomic_fetch_add_explicit(&x0, 1, memory_order_release);
	r2 = 0;
	r1 = atomic_compare_exchange_weak_explicit(&x1, &r2, 2, memory_order_acquire, memory_order_relaxed);
	r3 = atomic_load_explicit(&x0, memory_order_relaxed);
	atomic_store_explicit(&x0, 0, memory_order_relaxed);
	r4 = atomic_load_explicit(&x0, memory_order_seq_cst);
	return NULL;
}

void *t1(void *arg)
{
	int r0 = 0;
	int r1 = 0;
	int r2 = 0;
	int r3 = 0;
	int r4 = 0;
	r0 = atomic_load_explicit(&x0, memory_order_relaxed);
	if (r0) {
		r1 = atomic_fetch_add_explicit(&x1, 2, memory_order_release);
	}
	r3 = 1;
	r2 = atomic_compare_exchange_strong_explicit(&x1, &r3, 1, memory_order_relaxed, memory_order_relaxed);
	r4 = atomic_load_explicit(&x0, memory_order_seq_cst);
	return NULL;
}

void *t2(void *arg)
{
	int r0 = 0;
	r0 = atomic_load_explicit(&x0, memory_order_relaxed);
	atomic_thread_fence(memory_order_acq_rel);
	if (r0 == 1) {
		atomic_store_explicit(&x0, 1, memory_order_seq_cst);
	}
	atomic_store_explicit(&x1, 3, memory_order_release);
	return NULL;
}

int main(void)
{
	pthread_t h0, h1, h2;
	pthread_create(&h0, NULL, t0, NULL);
	pthread_create(&h1, NULL, t1, NULL);
	pthread_create(&h2, NULL, t2, NULL);
	pthread_join(h0, NULL);
	pthread_join(h1, NULL);
	pthread_join(h2, NULL);
	return 0;
}
