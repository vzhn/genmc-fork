/* Issue #119: under -imm, the number of executions explored depended on
 * the schedule. With the default (writes-first) policy the program has 33
 * executions, as under rc11 and with -exhaustive; an arbitrary schedule
 * (seeds 1 and 3) found 32.
 *
 * The lost execution: t0's fetch_add reads the initial value, its CAS
 * reads t2's x1 = 3 (and fails), its load of x0 reads its own fetch_add,
 * and it writes x0 = 0; t1 reads that 0; t2 reads the fetch_add (1), so it
 * writes x0 = 1 and then x1 = 3; the coherence order of x0 is fetch_add,
 * 0, 1. It needs t2's x1 = 3 to revisit t0's CAS backward, after which
 * t1's load is re-added; under the arbitrary schedule t1's load is added
 * before t0's x0 = 0, so the execution can only come from a backward
 * revisit of t1's load by x0 = 0, which deletes t0's load of x0 (it is
 * not in the ppo-prefix of x0 = 0, so it is a hole after the revisit).
 * That revisit was rejected as non-maximal: the load was judged by the
 * co-maximality of its rf when it was added, while a hole is re-executed
 * after the revisit, where x0 = 0, placed before x0 = 1, bounds its
 * choice to the fetch_add (which it reads).
 *
 * (Generated by scripts/fuzz-c11.py, seed 64, with a strong CAS.)
 */
#include <pthread.h>
#include <stdatomic.h>

atomic_int x0, x1;
int r0, r1, r2, r3, s0, u0;

void *t0(void *arg)
{
	r0 = atomic_fetch_add_explicit(&x0, 1, memory_order_relaxed);
	r1 = atomic_compare_exchange_strong_explicit(&x1, &r2, 2, memory_order_acquire,
						       memory_order_relaxed);
	r3 = atomic_load_explicit(&x0, memory_order_relaxed);
	atomic_store_explicit(&x0, 0, memory_order_relaxed);
	return NULL;
}

void *t1(void *arg)
{
	s0 = atomic_load_explicit(&x0, memory_order_relaxed);
	return NULL;
}

void *t2(void *arg)
{
	u0 = atomic_load_explicit(&x0, memory_order_relaxed);
	if (u0 == 1)
		atomic_store_explicit(&x0, 1, memory_order_seq_cst);
	atomic_store_explicit(&x1, 3, memory_order_relaxed);
	return NULL;
}

int main(void)
{
	pthread_t h0, h1, h2;
	pthread_create(&h0, NULL, t0, NULL);
	pthread_create(&h1, NULL, t1, NULL);
	pthread_create(&h2, NULL, t2, NULL);
	pthread_join(h0, NULL);
	pthread_join(h1, NULL);
	pthread_join(h2, NULL);
	return 0;
}
