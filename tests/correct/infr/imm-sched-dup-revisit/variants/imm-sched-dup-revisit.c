#include <pthread.h>
#include <stdatomic.h>

atomic_int x0;
atomic_int x1;
atomic_int x2;
atomic_int x3;

void *t0(void *arg)
{
	int r0 = 0;
	int r1 = 0;
	int r2 = 0;
	int r3 = 0;
	int r4 = 0;
	r0 = atomic_fetch_add_explicit(&x2, 2, memory_order_release);
	r1 = atomic_fetch_add_explicit(&x1, 1, memory_order_seq_cst);
	r2 = atomic_load_explicit(&x3, memory_order_seq_cst);
	r3 = atomic_load_explicit(&x3, memory_order_relaxed);
	r4 = atomic_load_explicit(&x1, memory_order_acquire);
	atomic_store_explicit(&x0, 2, memory_order_relaxed);
	return NULL;
}

void *t1(void *arg)
{
	int r0 = 0;
	int r1 = 0;
	int r2 = 0;
	r0 = atomic_load_explicit(&x0, memory_order_acquire);
	if (r0) {
		if (r0) {
			atomic_store_explicit(&x1, 0, memory_order_relaxed);
		}
		atomic_thread_fence(memory_order_acq_rel);
	}
	atomic_store_explicit(&x3, 0, memory_order_seq_cst);
	r1 = atomic_fetch_add_explicit(&x0, 2, memory_order_seq_cst);
	r2 = atomic_load_explicit(&x3, memory_order_acquire);
	return NULL;
}

void *t2(void *arg)
{
	int r0 = 0;
	int r1 = 0;
	atomic_store_explicit(&x0, 2, memory_order_seq_cst);
	atomic_store_explicit(&x1, 0, memory_order_seq_cst);
	atomic_store_explicit(&x0, 2, memory_order_seq_cst);
	atomic_store_explicit(&x2, 1, memory_order_seq_cst);
	r1 = 1;
	r0 = atomic_compare_exchange_strong_explicit(&x0, &r1, 0, memory_order_release, memory_order_relaxed);
	return NULL;
}

int main(void)
{
	pthread_t h0, h1, h2;
	pthread_create(&h0, NULL, t0, NULL);
	pthread_create(&h1, NULL, t1, NULL);
	pthread_create(&h2, NULL, t2, NULL);
	pthread_join(h0, NULL);
	pthread_join(h1, NULL);
	pthread_join(h2, NULL);
	return 0;
}
